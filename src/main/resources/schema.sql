CREATE TABLE IF NOT EXISTS transactions (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  external_id  VARCHAR(128) NOT NULL,
  type         VARCHAR(16)  NOT NULL,                 -- copy of the metadata subtype; set by the service
  currency     CHAR(3)      NOT NULL,
  occurred_at  TIMESTAMP WITH TIME ZONE NOT NULL,
  total        DECIMAL(19,4) NOT NULL,
  created_at   TIMESTAMP WITH TIME ZONE NOT NULL,
  updated_at   TIMESTAMP WITH TIME ZONE NOT NULL,
  CONSTRAINT uq_txn_external_id UNIQUE (external_id),
  CONSTRAINT ck_txn_type CHECK (type IN ('flight','hotel','rail','navan_fee'))
);

CREATE TABLE IF NOT EXISTS transaction_tax_lines (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  transaction_id BIGINT NOT NULL REFERENCES transactions(id) ON DELETE CASCADE,
  name VARCHAR(64) NOT NULL, rate DECIMAL(9,6) NULL, amount DECIMAL(19,4) NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_txntax_txn ON transaction_tax_lines (transaction_id);

CREATE TABLE IF NOT EXISTS transaction_fee_lines (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  transaction_id BIGINT NOT NULL REFERENCES transactions(id) ON DELETE CASCADE,
  name VARCHAR(64) NOT NULL, amount DECIMAL(19,4) NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_txnfee_txn ON transaction_fee_lines (transaction_id);

-- metadata: shared primary key with transactions --------------------------
CREATE TABLE IF NOT EXISTS transaction_metadata (
  transaction_id BIGINT PRIMARY KEY REFERENCES transactions(id) ON DELETE CASCADE
);

-- JOINED metadata subtype tables: PK = FK to transaction_metadata ---------
CREATE TABLE IF NOT EXISTS flight_details (
  transaction_id BIGINT PRIMARY KEY REFERENCES transaction_metadata(transaction_id) ON DELETE CASCADE,
  origin VARCHAR(64) NOT NULL, destination VARCHAR(64) NOT NULL, fare DECIMAL(19,4) NOT NULL
);
CREATE TABLE IF NOT EXISTS flight_coupons (            -- @ElementCollection
  transaction_id BIGINT NOT NULL REFERENCES flight_details(transaction_id) ON DELETE CASCADE,
  flight_number VARCHAR(16) NOT NULL, carrier VARCHAR(8) NULL,
  from_airport VARCHAR(64) NOT NULL, to_airport VARCHAR(64) NOT NULL,   -- "from"/"to" are reserved words
  departure TIMESTAMP WITH TIME ZONE NOT NULL, arrival TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_flight_coupons_txn ON flight_coupons(transaction_id);

CREATE TABLE IF NOT EXISTS hotel_details (
  transaction_id BIGINT PRIMARY KEY REFERENCES transaction_metadata(transaction_id) ON DELETE CASCADE,
  name VARCHAR(200) NOT NULL,
  street VARCHAR(200) NOT NULL, city VARCHAR(100) NOT NULL, country VARCHAR(64) NOT NULL,
  check_in DATE NOT NULL, check_out DATE NOT NULL,
  nights INT NOT NULL, room_rate_per_night DECIMAL(19,4) NOT NULL,
  extras_json TEXT NULL                                   -- opaque JSON, optional
);

CREATE TABLE IF NOT EXISTS rail_details (                 -- thin: JOINED requires a table per metadata subclass
  transaction_id BIGINT PRIMARY KEY REFERENCES transaction_metadata(transaction_id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS rail_legs (                    -- @ElementCollection
  transaction_id BIGINT NOT NULL REFERENCES rail_details(transaction_id) ON DELETE CASCADE,
  origin VARCHAR(100) NOT NULL, destination VARCHAR(100) NOT NULL,
  departure TIMESTAMP WITH TIME ZONE NOT NULL, arrival TIMESTAMP WITH TIME ZONE NOT NULL,
  train_number VARCHAR(16) NULL, service_class VARCHAR(32) NULL   -- JSON key is "class"
);
CREATE INDEX IF NOT EXISTS ix_rail_legs_txn ON rail_legs(transaction_id);

CREATE TABLE IF NOT EXISTS navan_fee_details (
  transaction_id BIGINT PRIMARY KEY REFERENCES transaction_metadata(transaction_id) ON DELETE CASCADE,
  fee_kind VARCHAR(32) NOT NULL, description VARCHAR(255) NULL, related_external_id VARCHAR(128) NULL,
  CONSTRAINT ck_fee_kind CHECK (fee_kind IN ('trip_fee','agent_call_fee'))
);

-- invoices (frozen snapshot) --------------------------------------------
CREATE TABLE IF NOT EXISTS invoices (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  currency CHAR(3) NOT NULL, total DECIMAL(19,4) NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL, updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE IF NOT EXISTS invoice_lines (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  invoice_id BIGINT NOT NULL REFERENCES invoices(id) ON DELETE CASCADE,
  transaction_id BIGINT NOT NULL REFERENCES transactions(id) ON DELETE RESTRICT,
  type VARCHAR(16) NOT NULL, external_id VARCHAR(128) NOT NULL, currency CHAR(3) NOT NULL,   -- frozen copy
  occurred_at TIMESTAMP WITH TIME ZONE NOT NULL, total DECIMAL(19,4) NOT NULL,
  metadata_json TEXT NOT NULL,
  CONSTRAINT uq_invline_inv_txn UNIQUE (invoice_id, transaction_id)   -- also serves WHERE invoice_id = ?
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_invline_txn ON invoice_lines (transaction_id);   -- one invoice per transaction; also supports membership checks

CREATE TABLE IF NOT EXISTS invoice_line_tax_lines (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  invoice_line_id BIGINT NOT NULL REFERENCES invoice_lines(id) ON DELETE CASCADE,
  name VARCHAR(64) NOT NULL, rate DECIMAL(9,6) NULL, amount DECIMAL(19,4) NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_iltax_line ON invoice_line_tax_lines (invoice_line_id);
CREATE TABLE IF NOT EXISTS invoice_line_fee_lines (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  invoice_line_id BIGINT NOT NULL REFERENCES invoice_lines(id) ON DELETE CASCADE,
  name VARCHAR(64) NOT NULL, amount DECIMAL(19,4) NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_ilfee_line ON invoice_line_fee_lines (invoice_line_id);
